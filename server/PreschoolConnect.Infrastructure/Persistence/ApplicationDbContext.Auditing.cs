using System.Text.Json;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.ChangeTracking;
using PreschoolConnect.Application.Models;

namespace PreschoolConnect.Infrastructure.Persistence;

public partial class ApplicationDbContext
{
    private static readonly string[] AuditProperties =
    [
        nameof(BaseAuditableEntity.CreatedAtUtc), nameof(BaseAuditableEntity.CreatedByUserId),
        nameof(BaseAuditableEntity.LastAction), nameof(BaseAuditableEntity.LastActionByUserId),
        nameof(BaseAuditableEntity.LastActionAtUtc)
    ];
    private static readonly HashSet<string> AuditedBusinessFields =
    [
        "Name", "Slug", "IsActive", "StartDate", "EndDate", "SchoolYearId",
        "FirstName", "LastName", "PreferredName", "DateOfBirth",
        "Guardian", "Relationship", "Pickup", "Emergency", "AgeGroup", "StudyMode",
        "Degree", "Graduated", "University", "Experience", "StartDate", "Contract", "Work",
        "Role", "StartedAtUtc", "EndedAtUtc", "UserId", "Gender", "Phone", "Email", "Address", "Birthday", "Certificate"
    ];

    public override int SaveChanges(bool acceptAllChangesOnSuccess)
    {
        var batch = PrepareAuditAsync(false, CancellationToken.None).GetAwaiter().GetResult();
        try { return base.SaveChanges(acceptAllChangesOnSuccess); }
        catch { RollbackAudit(batch); throw; }
    }

    public override async Task<int> SaveChangesAsync(bool acceptAllChangesOnSuccess, CancellationToken cancellationToken = default)
    {
        var batch = await PrepareAuditAsync(true, cancellationToken);
        try { return await base.SaveChangesAsync(acceptAllChangesOnSuccess, cancellationToken); }
        catch { RollbackAudit(batch); throw; }
    }

    private sealed record AuditBackup(EntityEntry Entry, EntityState State, PropertyValues Values, PropertyValues OriginalValues, string[] ModifiedFields);
    private sealed record AuditBatch(List<AuditBackup> Backups, List<AuditLog> Logs);

    private async Task<AuditBatch> PrepareAuditAsync(bool async, CancellationToken cancellationToken)
    {
        ChangeTracker.DetectChanges();
        if (ChangeTracker.Entries<AuditLog>().Any(entry => entry.State is EntityState.Added or EntityState.Modified or EntityState.Deleted))
            throw new InvalidOperationException("AuditLogs are append-only and generated by the auditing pipeline.");
        var entries = ChangeTracker.Entries<BaseAuditableEntity>()
            .Where(entry => entry.State is EntityState.Added or EntityState.Modified or EntityState.Deleted).ToList();
        var grants = ChangeTracker.Entries<SchoolMembershipRole>()
            .Where(entry => entry.State is EntityState.Added or EntityState.Modified or EntityState.Deleted).ToList();
        var batch = new AuditBatch([], []);
        if (entries.Count == 0 && grants.Count == 0) return batch;
        var actor = auditActorProvider?.GetActor() ??
            throw new InvalidOperationException("No audit actor provider was supplied for business writes.");
        if ((actor.UserId is null) == (actor.SystemOperation is null))
            throw new InvalidOperationException("Exactly one authenticated actor or named system operation is required.");
        if (actor.UserId is null && (string.IsNullOrWhiteSpace(actor.SystemOperation) || actor.SystemOperation.Length > 100))
            throw new InvalidOperationException("System audit operation names must contain 1-100 characters.");
        var clock = DateTimeOffset.UtcNow;
        var now = new DateTimeOffset(clock.Ticks - clock.Ticks % 10, TimeSpan.Zero);
        // Validate the entire batch before stamping any entry.
        foreach (var entry in entries)
        {
            var id = (Guid)entry.Property("Id").CurrentValue!;
            var schoolId = entry.Entity is School ? id : (Guid)entry.Property("SchoolId").CurrentValue!;
            await ValidateActorAsync(actor.UserId, schoolId, async, cancellationToken);
            if (entry.State != EntityState.Added)
            {
                var stored = async ? await entry.GetDatabaseValuesAsync(cancellationToken) : entry.GetDatabaseValues();
                if (stored is null) throw new DbUpdateConcurrencyException("Business record no longer exists.");
                if ((string)stored[nameof(BaseAuditableEntity.LastAction)]! == "D")
                    throw new AuditPolicyException("Soft-deleted business records cannot be updated or restored.");
                foreach (var property in AuditProperties)
                    if (!Equals(entry.Property(property).CurrentValue, stored[property]))
                        throw new DbUpdateConcurrencyException("Audit metadata cannot be supplied or changed; reload the record.");
                if (entry.Metadata.FindProperty("CreatedUtc") is not null && !Equals(entry.Property("CreatedUtc").CurrentValue, stored["CreatedUtc"]))
                    throw new AuditPolicyException("Legacy creation metadata is immutable.");
                if (!Equals(entry.Property("Id").CurrentValue, stored["Id"]) ||
                    (entry.Entity is not School && !Equals(entry.Property("SchoolId").CurrentValue, stored["SchoolId"])))
                    throw new AuditPolicyException("Business identity and school ownership are immutable.");
                if (entry.Entity is StudentAccount &&
                    (!Equals(entry.Property(nameof(StudentAccount.UserId)).CurrentValue, stored[nameof(StudentAccount.UserId)]) ||
                     !Equals(entry.Property(nameof(StudentAccount.StudentId)).CurrentValue, stored[nameof(StudentAccount.StudentId)])))
                    throw new AuditPolicyException("Student-account identity cannot be reassigned.");
                if (entry.Entity is SchoolMembership && !Equals(entry.Property(nameof(SchoolMembership.UserId)).CurrentValue, stored[nameof(SchoolMembership.UserId)]))
                    throw new AuditPolicyException("Membership identity cannot be reassigned.");
                if (entry.Entity is Classroom && !Equals(entry.Property(nameof(Classroom.SchoolYearId)).CurrentValue, stored[nameof(Classroom.SchoolYearId)]))
                    throw new AuditPolicyException("A classroom's original school year cannot be changed.");
                if (entry.Entity is Teacher && stored[nameof(Teacher.UserId)] is Guid linkedUser &&
                    !Equals(entry.Property(nameof(Teacher.UserId)).CurrentValue, linkedUser))
                    throw new AuditPolicyException("A linked teacher identity cannot be reassigned.");
                if (entry.Entity is TeacherAssignment &&
                    (!Equals(entry.Property(nameof(TeacherAssignment.TeacherId)).CurrentValue, stored[nameof(TeacherAssignment.TeacherId)]) ||
                     !Equals(entry.Property(nameof(TeacherAssignment.ClassroomId)).CurrentValue, stored[nameof(TeacherAssignment.ClassroomId)]) ||
                     !Equals(entry.Property(nameof(TeacherAssignment.StartedAtUtc)).CurrentValue, stored[nameof(TeacherAssignment.StartedAtUtc)]) ||
                     !Equals(entry.Property(nameof(TeacherAssignment.Role)).CurrentValue, stored[nameof(TeacherAssignment.Role)]) ||
                     entry.Property(nameof(TeacherAssignment.EndedAtUtc)).CurrentValue is null ||
                     stored[nameof(TeacherAssignment.EndedAtUtc)] is not null))
                    throw new AuditPolicyException("Assignment history is immutable except for ending an active assignment.");
                if (entry.Entity is StudentInClass)
                {
                    var today = DateOnly.FromDateTime(TimeZoneInfo.ConvertTimeBySystemTimeZoneId(DateTimeOffset.UtcNow, "Asia/Ho_Chi_Minh").DateTime);
                    if (entry.State == EntityState.Deleted ||
                        new[] { "StudentId", "ClassroomId", "StartDate", "AgeGroup", "StudyMode" }
                            .Any(name => !Equals(entry.Property(name).CurrentValue, stored[name])) ||
                        (DateOnly)stored["EndDate"]! <= today || (DateOnly)stored["StartDate"]! >= today ||
                        (DateOnly)entry.Property("EndDate").CurrentValue! != today)
                        throw new AuditPolicyException("Enrollment history may only be ended today; identity and prior periods are immutable.");
                }
            }
            await ValidateActiveParentsAsync(entry, async, cancellationToken);
            if (entry.State == EntityState.Deleted) await ValidateDeletionAsync(entry, async, cancellationToken);
            if (entry.Entity is SchoolYear year && entry.State == EntityState.Modified &&
                (entry.Property(nameof(SchoolYear.StartDate)).IsModified || entry.Property(nameof(SchoolYear.EndDate)).IsModified) &&
                await ExistsAsync(Classrooms.IgnoreQueryFilters().Where(item => item.SchoolId == year.SchoolId && item.SchoolYearId == year.Id), async, cancellationToken))
                throw new AuditPolicyException("A school year referenced by classes cannot change dates.");
            if (entry.Entity is Student changedStudent && entry.State == EntityState.Modified &&
                entry.Property(nameof(Student.DateOfBirth)).IsModified &&
                await ExistsAsync(StudentInClasses.IgnoreQueryFilters().Where(item => item.SchoolId == changedStudent.SchoolId &&
                    item.StudentId == changedStudent.Id && item.StartDate < changedStudent.DateOfBirth), async, cancellationToken))
                throw new AuditPolicyException("A student's birthday cannot follow retained enrollment history.");
        }
        foreach (var grant in grants)
        {
            var member = ChangeTracker.Entries<SchoolMembership>().Select(item => item.Entity)
                .SingleOrDefault(item => item.Id == grant.Entity.MembershipId);
            member ??= async
                ? await SchoolMemberships.SingleOrDefaultAsync(item => item.Id == grant.Entity.MembershipId, cancellationToken)
                : SchoolMemberships.SingleOrDefault(item => item.Id == grant.Entity.MembershipId);
            if (member is null || member.LastAction == "D" || Entry(member).State == EntityState.Deleted)
                throw new AuditPolicyException("Permission changes require a non-deleted membership.");
            if (Entry(member).State != EntityState.Added &&
                !await ExistsAsync(SchoolMemberships.Where(item => item.Id == member.Id && item.SchoolId == member.SchoolId), async, cancellationToken))
                throw new AuditPolicyException("Permission changes require a non-deleted membership.");
            await ValidateActorAsync(actor.UserId, member.SchoolId, async, cancellationToken);
            batch.Logs.Add(AuditLog.Record(member.SchoolId, nameof(SchoolMembershipRole), member.Id,
                grant.State == EntityState.Deleted ? "D" : grant.State == EntityState.Added ? "I" : "U",
                actor.UserId, actor.SystemOperation, now, "[\"Role\"]"));
        }
        foreach (var entry in entries)
        {
            batch.Backups.Add(new(entry, entry.State, entry.CurrentValues.Clone(), entry.OriginalValues.Clone(),
                entry.Properties.Where(property => property.IsModified).Select(property => property.Metadata.Name).ToArray()));
            var action = entry.State == EntityState.Added ? "I" : entry.State == EntityState.Deleted ? "D" : "U";
            var changedFields = entry.Properties.Where(property => property.IsModified && AuditedBusinessFields.Contains(property.Metadata.Name) &&
                    !Equals(property.CurrentValue, property.OriginalValue))
                .Select(property => property.Metadata.Name).Order().ToArray();
            if (entry.State == EntityState.Deleted)
            {
                entry.State = EntityState.Unchanged;
            }
            if (action == "I")
            {
                entry.Property(nameof(BaseAuditableEntity.CreatedAtUtc)).CurrentValue = now;
                entry.Property(nameof(BaseAuditableEntity.CreatedByUserId)).CurrentValue = actor.UserId;
                if (entry.Metadata.FindProperty("CreatedUtc") is not null) entry.Property("CreatedUtc").CurrentValue = now;
            }
            entry.Property(nameof(BaseAuditableEntity.LastAction)).CurrentValue = action;
            entry.Property(nameof(BaseAuditableEntity.LastActionByUserId)).CurrentValue = actor.UserId;
            var created = (DateTimeOffset)entry.Property(nameof(BaseAuditableEntity.CreatedAtUtc)).CurrentValue!;
            var previous = (DateTimeOffset)entry.Property(nameof(BaseAuditableEntity.LastActionAtUtc)).CurrentValue!;
            var timestamp = now > previous ? now : previous.AddTicks(10);
            if (timestamp < created) timestamp = created;
            entry.Property(nameof(BaseAuditableEntity.LastActionAtUtc)).CurrentValue = timestamp;
            if (action != "I")
            {
                entry.Property(nameof(BaseAuditableEntity.LastAction)).IsModified = true;
                entry.Property(nameof(BaseAuditableEntity.LastActionByUserId)).IsModified = true;
                entry.Property(nameof(BaseAuditableEntity.LastActionAtUtc)).IsModified = true;
            }
            var id = (Guid)entry.Property("Id").CurrentValue!;
            var schoolId = entry.Entity is School ? id : (Guid)entry.Property("SchoolId").CurrentValue!;
            batch.Logs.Add(AuditLog.Record(schoolId, entry.Metadata.ClrType.Name, id, action, actor.UserId,
                actor.SystemOperation, timestamp, JsonSerializer.Serialize(action == "U" ? changedFields : [])));
        }
        AuditLogs.AddRange(batch.Logs);
        return batch;
    }

    private async Task ValidateDeletionAsync(EntityEntry<BaseAuditableEntity> entry, bool async, CancellationToken cancellationToken)
    {
        var blocked = entry.Entity switch
        {
            School school => await ExistsAsync(SchoolYears.IgnoreQueryFilters().Where(item => item.SchoolId == school.Id), async, cancellationToken) ||
                await ExistsAsync(SchoolMemberships.IgnoreQueryFilters().Where(item => item.SchoolId == school.Id), async, cancellationToken) ||
                await ExistsAsync(Students.IgnoreQueryFilters().Where(item => item.SchoolId == school.Id), async, cancellationToken),
            SchoolYear year => await ExistsAsync(Classrooms.IgnoreQueryFilters().Where(item => item.SchoolId == year.SchoolId && item.SchoolYearId == year.Id), async, cancellationToken),
            Student student => await ExistsAsync(StudentAccounts.IgnoreQueryFilters().Where(item => item.SchoolId == student.SchoolId && item.StudentId == student.Id), async, cancellationToken) ||
                await ExistsAsync(StudentInClasses.IgnoreQueryFilters().Where(item => item.SchoolId == student.SchoolId && item.StudentId == student.Id), async, cancellationToken),
            Classroom classroom => await ExistsAsync(StudentInClasses.IgnoreQueryFilters().Where(item => item.SchoolId == classroom.SchoolId && item.ClassroomId == classroom.Id), async, cancellationToken),
            StudentInClass => true,
            _ => false
        };
        if (blocked) throw new AuditPolicyException("This business record has retained dependent records and cannot be soft deleted.");
    }

    private static Task<bool> ExistsAsync<T>(IQueryable<T> query, bool async, CancellationToken cancellationToken) =>
        async ? query.AnyAsync(cancellationToken) : Task.FromResult(query.Any());

    private async Task ValidateActorAsync(Guid? actorId, Guid schoolId, bool async, CancellationToken cancellationToken)
    {
        if (actorId is null) return;
        var validUser = await ExistsAsync(Users.Where(user => user.Id == actorId && user.IsActive), async, cancellationToken);
        var validMembership = await ExistsAsync(SchoolMemberships.Where(member => member.UserId == actorId && member.SchoolId == schoolId && member.IsActive &&
            Schools.Any(school => school.Id == schoolId && school.IsActive)), async, cancellationToken);
        if (!validUser || !validMembership)
            throw new AuditPolicyException("The audit actor must be active and authorized in the entity's school.");
    }

    private async Task ValidateActiveParentsAsync(EntityEntry<BaseAuditableEntity> entry, bool async, CancellationToken cancellationToken)
    {
        if (entry.State == EntityState.Deleted || entry.Entity is School) return;
        var schoolId = (Guid)entry.Property("SchoolId").CurrentValue!;
        if (ChangeTracker.Entries<School>().Any(item => item.State == EntityState.Deleted && item.Entity.Id == schoolId))
            throw new AuditPolicyException("Business writes cannot target a school being deleted in the same transaction.");
        var newSchool = ChangeTracker.Entries<School>().Any(item => item.State == EntityState.Added && item.Entity.Id == schoolId);
        if (!newSchool && !await ExistsAsync(Schools.Where(item => item.Id == schoolId && item.IsActive), async, cancellationToken))
            throw new AuditPolicyException("Business writes require an active, non-deleted school.");
        if (entry.Entity is Classroom classroom && (entry.State == EntityState.Added || entry.Property(nameof(Classroom.SchoolYearId)).IsModified))
        {
            if (ChangeTracker.Entries<SchoolYear>().Any(item => item.State == EntityState.Deleted && item.Entity.Id == classroom.SchoolYearId))
                throw new AuditPolicyException("Classes cannot target a school year being deleted in the same transaction.");
            var newYear = ChangeTracker.Entries<SchoolYear>().Any(item => item.State == EntityState.Added && item.Entity.Id == classroom.SchoolYearId && item.Entity.SchoolId == schoolId);
            if (!newYear && !await ExistsAsync(SchoolYears.Where(item => item.Id == classroom.SchoolYearId && item.SchoolId == schoolId), async, cancellationToken))
                throw new AuditPolicyException("Classes require a non-deleted school year in the same school.");
        }
        if (entry.Entity is StudentAccount account)
        {
            if (ChangeTracker.Entries<Student>().Any(item => item.State == EntityState.Deleted && item.Entity.Id == account.StudentId))
                throw new AuditPolicyException("Account mappings cannot target a student being deleted in the same transaction.");
            var newStudent = ChangeTracker.Entries<Student>().Any(item => item.State == EntityState.Added && item.Entity.Id == account.StudentId && item.Entity.SchoolId == schoolId);
            if (!newStudent && !await ExistsAsync(Students.Where(item => item.Id == account.StudentId && item.SchoolId == schoolId), async, cancellationToken))
                throw new AuditPolicyException("Student accounts require a non-deleted student in the same school.");
        }
        if (entry.Entity is StudentInClass enrollment && entry.State == EntityState.Added)
        {
            var student = async
                ? await Students.SingleOrDefaultAsync(row => row.Id == enrollment.StudentId && row.SchoolId == schoolId, cancellationToken)
                : Students.SingleOrDefault(row => row.Id == enrollment.StudentId && row.SchoolId == schoolId);
            var enrollmentClass = async
                ? await Classrooms.SingleOrDefaultAsync(row => row.Id == enrollment.ClassroomId && row.SchoolId == schoolId, cancellationToken)
                : Classrooms.SingleOrDefault(row => row.Id == enrollment.ClassroomId && row.SchoolId == schoolId);
            var year = enrollmentClass is null ? null : async
                ? await SchoolYears.SingleOrDefaultAsync(row => row.Id == enrollmentClass.SchoolYearId && row.SchoolId == schoolId, cancellationToken)
                : SchoolYears.SingleOrDefault(row => row.Id == enrollmentClass.SchoolYearId && row.SchoolId == schoolId);
            var today = DateOnly.FromDateTime(TimeZoneInfo.ConvertTimeBySystemTimeZoneId(DateTimeOffset.UtcNow, "Asia/Ho_Chi_Minh").DateTime);
            if (student is null || year is null || year.EndDate == DateOnly.MaxValue ||
                enrollment.StartDate < student.DateOfBirth || enrollment.StartDate < year.StartDate ||
                enrollment.StartDate > today || enrollment.StartDate > year.EndDate ||
                enrollment.EndDate != year.EndDate.AddDays(1) ||
                enrollment.AgeGroup is not ("Mầm · 3–4 tuổi" or "Chồi · 4–5 tuổi" or "Lá · 5–6 tuổi") ||
                enrollment.StudyMode is not ("Bán trú" or "Cả ngày"))
                throw new AuditPolicyException("Enrollment requires valid same-school student/class/year and a school-year-bounded period.");
            var history = StudentInClasses.IgnoreQueryFilters().Where(row => row.SchoolId == schoolId && row.StudentId == enrollment.StudentId);
            if (enrollment.StartDate != today && await ExistsAsync(history, async, cancellationToken) ||
                await ExistsAsync(history.Where(row => row.StartDate < enrollment.EndDate && enrollment.StartDate < row.EndDate), async, cancellationToken))
                throw new AuditPolicyException("Enrollment periods cannot overlap and re-enrollment must start today.");
        }
        if (entry.Entity is Teacher teacher && teacher.UserId.HasValue &&
            (entry.State == EntityState.Added || entry.Property(nameof(Teacher.UserId)).IsModified) &&
            !await ExistsAsync(Users.Where(user => user.Id == teacher.UserId && user.IsActive &&
                SchoolMemberships.Any(member => member.UserId == user.Id && member.SchoolId == schoolId &&
                    member.IsActive && member.Roles.Any(role => role.Role == SchoolRoleNames.Teacher))), async, cancellationToken))
            throw new AuditPolicyException("Teacher account links require an active Teacher membership in the same school.");
        if (entry.Entity is TeacherAssignment assignment && entry.State == EntityState.Added &&
            (!await ExistsAsync(Teachers.Where(teacher => teacher.Id == assignment.TeacherId && teacher.SchoolId == schoolId && teacher.IsActive), async, cancellationToken) ||
             !await ExistsAsync(Classrooms.Where(classroom => classroom.Id == assignment.ClassroomId && classroom.SchoolId == schoolId &&
                SchoolYears.Any(year => year.Id == classroom.SchoolYearId && year.SchoolId == schoolId)), async, cancellationToken)))
            throw new AuditPolicyException("Assignments require an active teacher and a non-deleted class/year in the same school.");
    }

    private void RollbackAudit(AuditBatch batch)
    {
        foreach (var log in batch.Logs) Entry(log).State = EntityState.Detached;
        foreach (var backup in batch.Backups)
        {
            backup.Entry.CurrentValues.SetValues(backup.Values);
            backup.Entry.OriginalValues.SetValues(backup.OriginalValues);
            backup.Entry.State = backup.State;
            if (backup.State == EntityState.Modified)
                foreach (var property in backup.Entry.Properties)
                    property.IsModified = backup.ModifiedFields.Contains(property.Metadata.Name);
        }
    }
}
